import assert from "node:assert/strict";
import {
  existsSync,
  readFileSync,
  readdirSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDirectory = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptsDirectory, "..");
const readJson = relativePath =>
  JSON.parse(readFileSync(path.join(repoRoot, relativePath), "utf8"));

const packageJson = readJson("package.json");
const manifest = readJson("plugin/manifest.json");
const buildScript = readFileSync(path.join(repoRoot, "scripts/build-plugin.js"), "utf8");
const builtPlugin = readFileSync(path.join(repoRoot, "plugin/code.js"), "utf8");
const writeHandlers = readFileSync(
  path.join(repoRoot, "src/plugin/handlers-write.js"),
  "utf8",
);
const readHelpers = readFileSync(
  path.join(repoRoot, "src/plugin/read-helpers.js"),
  "utf8",
);

assert.equal(packageJson.private, true, "The source-only package must not publish to npm.");
for (const relativePath of packageJson.files) {
  assert.ok(existsSync(path.join(repoRoot, relativePath)), `Missing package file: ${relativePath}`);
}

for (const key of ["main", "ui"]) {
  const relativePath = path.join("plugin", manifest[key]);
  assert.ok(existsSync(path.join(repoRoot, relativePath)), `Missing manifest ${key}: ${relativePath}`);
}

const expectedBridgeDomains = Array.from(
  { length: 10 },
  (_, index) => `http://localhost:${38451 + index}`,
);
assert.deepEqual(
  manifest.networkAccess.allowedDomains,
  expectedBridgeDomains,
  "Manifest bridge domains must match the runtime fallback port range.",
);

const pluginSources = readdirSync(path.join(repoRoot, "src/plugin"))
  .filter(name => name.endsWith(".js"))
  .sort();
for (const name of pluginSources) {
  assert.match(buildScript, new RegExp(`src/plugin/${name.replace(".", "\\.")}`));
}
assert.match(builtPlugin, /AUTO-GENERATED by scripts\/build-plugin\.js/);
assert.match(writeHandlers, /setPluginData\("figmaUiMcpAsset"/);
assert.match(readHelpers, /getPluginData\("figmaUiMcpAsset"/);

const retiredPaths = [
  "plugin.zip",
  "plugin/icon16.png",
  "plugin/icon32.png",
  "assets/cover.png",
  "assets/logo.png",
  "assets/logo-icon.png",
  "assets/logo-v6.png",
  "assets/plugin-icon-128.png",
  "glama.json",
  "smithery.yaml",
  "server.json",
  "KIETTT8_SETUP.md",
];
for (const relativePath of retiredPaths) {
  assert.equal(
    existsSync(path.join(repoRoot, relativePath)),
    false,
    `Retired file returned: ${relativePath}`,
  );
}

console.log("Source-integrity tests passed.");
